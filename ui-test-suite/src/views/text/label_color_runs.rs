#[view]
struct LabelColorRuns {
    #[init]
    plain:   Label,
    runs:    Label,
    wrapped: Label,
    overlap: Label,
}

fn runs() -> Vec<(std::ops::Range<usize>, UIColor)> {
    vec![(0..3, KEYWORD), (20..22, NUMBER), (24..30, COMMENT)]
}

impl Setup for LabelColorRuns {
    fn setup(self: Weak<Self>) {
        for label in [self.plain, self.runs] {
            label.set_color(WHITE).set_text_color(BLACK).set_text_size(24);
            label.set_text(CODE).set_alignment(TextAlignment::Left).set_letter_spacing(1);
        }

        self.plain.set_frame(PLAIN_FRAME);
        self.runs.set_frame(RUNS_FRAME);
        // Black runs first, the real colors come once the shape is proven.
        self.runs
            .set_color_runs(runs().into_iter().map(|(range, _)| (range, UIColor::Plain(BLACK))));

        // A run that crosses a wrap keeps its color on both lines.
        self.wrapped.set_color(WHITE).set_text_color(BLACK).set_text_size(24);
        self.wrapped.set_text("keyword and a comment that wraps to the next line");
        self.wrapped.set_multiline(true).set_alignment(TextAlignment::Left);
        self.wrapped.place().t(160).lr(20).h(90);
        self.wrapped.set_color_runs(vec![(0..7, KEYWORD), (14..50, COMMENT)]);

        // Overlapping and out of range ranges: the later wins, the rest
        // is clamped, and the untouched tail stays the text color.
        self.overlap.set_color(WHITE).set_text_color(BLACK).set_text_size(24);
        self.overlap.set_text("overlap wins").set_alignment(TextAlignment::Left);
        self.overlap.place().t(270).lr(20).h(50);
        self.overlap
            .set_color_runs(vec![(0..7, KEYWORD), (3..7, NUMBER), (8..100, COMMENT)]);
    }
}

impl ViewTest for LabelColorRuns {
    fn perform_test(view: Weak<Self>) -> Result<()> {
        set_record_probe_count(800);
        from_main(|| Theme::set_mode(ThemeMode::Light));

        // Runs change colors and nothing else. With every run black the
        // label renders pixel for pixel like its plain twin.
        let shot = AppRunner::take_screenshot()?;
        assert!(
            region(&shot, PLAIN_FRAME) == region(&shot, RUNS_FRAME),
            "color runs moved glyphs"
        );

        from_main(move || {
            view.runs.set_color_runs(runs());
        });

        check_colors(LIGHT)?;

        // A dark theme re-resolves the themed run.
        from_main(|| Theme::set_mode(ThemeMode::Dark));
        check_colors(DARK)?;
        from_main(|| Theme::set_mode(ThemeMode::Light));

        // A new text drops the runs, they were ranges of the old one.
        from_main(move || {
            view.runs.set_text("plain again");
            assert_eq!(view.runs.color_runs_len(), 0);
        });
        check_colors(CLEARED)?;

        from_main(|| Theme::set_mode(ThemeMode::System));
        Ok(())
    }
}

fn region(shot: &Screenshot, frame: (u32, u32, u32, u32)) -> Vec<U8Color> {
    let (x, y, w, h) = frame;
    let mut pixels = Vec::with_capacity((w * h) as usize);

    for row in y..y + h {
        for col in x..x + w {
            pixels.push(shot.get_pixel((col, row)));
        }
    }

    pixels
}
