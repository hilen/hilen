/// The label widths walked, 100 to 280 in steps of 20. Every width
/// gets its own color block, so a wrap that moves at one width only
/// still fails.
const WIDTHS: [f32; 10] = [
    120.0, 140.0, 160.0, 180.0, 200.0, 220.0, 240.0, 260.0, 280.0, 300.0,
];

// One script per label. Japanese has no spaces and breaks between
// characters by the Unicode rules. Thai has no spaces and no rule
// without a dictionary, so an overlong piece breaks at the glyph that
// overflows. Korean has spaces and breaks at them like Latin.
const JAPANESE: &str = "日本語の文字も同じ行の中で折り返します。";
const THAI: &str = "ข้อความภาษาไทยก็ตัดบรรทัดได้เช่นกัน";
const KOREAN: &str = "한국어 문장도 단어 단위로 줄이 바뀝니다.";

/// Wrapping of scripts without spaces. Before the Unicode line break
/// rules the wrapper broke only at spaces, so a Japanese or Thai
/// sentence stayed one line and overflowed the label on both sides.
/// All of them in one label after a Latin sentence, each script in
/// its own font run, the demo's Fonts page case.
const MIXED: &str = concat!(
    "Wraps to its width. ",
    "日本語の文字も同じ行の中で折り返します。",
    "ข้อความภาษาไทยก็ตัดบรรทัดได้เช่นกัน ",
    "한국어 문장도 단어 단위로 줄이 바뀝니다.",
);

#[view]
struct ScriptWrap {
    #[init]
    japanese: Label,
    thai:     Label,
    korean:   Label,
    mixed:    Label,
}

impl Setup for ScriptWrap {
    fn setup(self: Weak<Self>) {
        for (label, text, font) in [
            (self.japanese, JAPANESE, "NotoSansJP-Regular.ttf"),
            (self.thai, THAI, "NotoSansThai.ttf"),
            (self.korean, KOREAN, "NotoSansKR-Regular.ttf"),
        ] {
            label
                .set_text(text)
                .set_color(WHITE)
                .set_text_color(BLACK)
                .set_text_size(20)
                .set_multiline(true)
                .set_alignment(TextAlignment::Left)
                .set_vertical_alignment(VerticalAlignment::Top);
            label.set_font_runs([(0..text.len(), RunStyle::font(Font::get(font)))]);
        }

        self.mixed
            .set_text(MIXED)
            .set_color(WHITE)
            .set_text_color(BLACK)
            .set_text_size(20)
            .set_multiline(true)
            .set_alignment(TextAlignment::Center)
            .set_vertical_alignment(VerticalAlignment::Top);
        self.mixed.set_font_runs([
            (
                part(JAPANESE),
                RunStyle::font(Font::get("NotoSansJP-Regular.ttf")),
            ),
            (part(THAI), RunStyle::font(Font::get("NotoSansThai.ttf"))),
            (part(KOREAN), RunStyle::font(Font::get("NotoSansKR-Regular.ttf"))),
        ]);
        self.resize(WIDTHS[0]);
    }
}

impl ScriptWrap {
    fn resize(self: Weak<Self>, width: f32) {
        self.japanese.set_frame((20.0, 20.0, width, 180.0));
        self.thai.set_frame((20.0, 220.0, width, 180.0));
        self.korean.set_frame((20.0, 420.0, width, 180.0));
        self.mixed.set_frame((320.0, 20.0, width, 580.0));
    }
}

fn part(text: &str) -> Range<usize> {
    let start = MIXED.find(text).expect("every script is in the mixed text");
    start..start + text.len()
}

fn check_lines(label: Weak<Label>, name: &str, width: f32) -> Result<()> {
    let layout = label.text_layout_for(label.text());
    ensure!(
        layout.lines.len() > 1,
        "{name} did not wrap, {} line",
        layout.lines.len()
    );
    for (index, line) in layout.lines.iter().enumerate() {
        ensure!(
            line.width <= width,
            "{name} line {index} is {} wide, the bound is {width}",
            line.width
        );
        ensure!(
            line.width > 0.0 && line.end > line.start,
            "{name} line {index} is empty"
        );
    }
    Ok(())
}

impl ViewTest for ScriptWrap {
    fn perform_test(view: Weak<Self>) -> Result<()> {
        set_record_probe_count(160);

        for (index, width) in WIDTHS.into_iter().enumerate() {
            from_main(move || view.resize(width));
            wait_for_next_frame();
            wait_for_next_frame();

            from_main(move || -> Result<()> {
                check_lines(view.japanese, "japanese", width)?;
                check_lines(view.thai, "thai", width)?;
                check_lines(view.korean, "korean", width)?;
                check_lines(view.mixed, "mixed", width)
            })?;

            check_colors(BLOCKS[index])?;
        }

        Ok(())
    }
}

