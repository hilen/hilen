// The margins differ, so a cell shifted by the wrong side shows up.
// The backdrop has a color no cell uses and fills both margin strips.
#[view]
struct TableMarginsTest {
    #[init]
    under: Container,
    table: TableView,
}

impl Setup for TableMarginsTest {
    fn setup(mut self: Weak<Self>) {
        self.under.set_color(BACKDROP);
        self.under.place().tl(0).size(400, 600);

        self.table.place().tl(0).size(400, 600);
        self.table.set_data_source(self).register_cell::<Container>();
        self.table.set_cell_spacing(16);
        self.table.set_cell_margins(20, 40);
        self.table.set_columns(2);
        self.table.reload_data();
    }
}

impl TableData for TableMarginsTest {
    fn cell_height(&self, _: usize) -> f32 {
        90.0
    }

    fn number_of_cells(&self) -> usize {
        12
    }

    fn setup_cell(&mut self, index: usize, registry: &mut CellRegistry) -> Weak<dyn View> {
        let cell = registry.cell::<Container>();
        cell.set_color(PALETTE[index % PALETTE.len()]);
        cell
    }

    fn cell_selected(&mut self, index: usize) {
        *SELECTED.lock() += &format!("|{index}|");
    }
}

