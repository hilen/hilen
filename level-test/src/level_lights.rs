/// A dark cave: a brick wall far behind, a stone floor, a cutout, a plain
/// box and a round polygon, so every level pipeline is lit, under a dim
/// ambient with a warm torch on the left and a blue lamp on the right. Then the
/// torch walks over to the lamp, the left side goes dark and the right one gets
/// warm.
#[level]
#[derive(Default)]
struct LevelLights {
    torch: Weak<Light>,
}

impl LevelSetup for LevelLights {
    fn setup(&mut self) {
        let mut stone = "game/tile_stone.png".to_image();
        stone.set_filter(ImageFilter::Nearest);

        let mut floor = TileMap::new(12, 2);
        floor.tile_size = 5.0;
        floor.origin = Point::new(-30.0, -30.0);
        let kind = floor.add_kind(TileKind::solid(stone));
        floor.fill(0, 0, 12, 2, kind);
        self.add_tile_map(floor);

        self.make_sprite::<Banner>(Shape::Rect((60, 60).into()), (0, 0))
            .set_image("bricks.jpg")
            .to_background();

        self.make_sprite::<Banner>(Shape::Rect((6, 10).into()), (-15, -10))
            .set_image("game/frisk.png");
        self.make_sprite::<Banner>(Shape::rect(8, 8), (2, -14))
            .set_color(Color::hex("#e0e0e0"));
        self.make_sprite::<Banner>(Shape::Circle(4.0), (18, -14)).set_color(GREEN);

        self.ambient_light = Color::hex("#202030");
        self.torch = self.add_light(
            Light::new((-15, -5), 30)
                .with_color(Color::hex("#ffb050"))
                .with_intensity(1.3)
                .with_falloff(1.2),
        );
        self.add_light(Light::new((18, -5), 22).with_color(Color::hex("#5080ff")).with_falloff(1.2));
    }
}

impl LevelTest for LevelLights {
    fn perform_test(level: Weak<Self>) -> Result<()> {
        set_record_probe_count(160);
        check_colors(TORCH_LEFT)?;

        from_main(move || {
            let mut torch = level.torch;
            torch.position = Point::new(12.0, -5.0);
        });
        wait_for_next_frame();

        check_colors(TORCH_RIGHT)
    }
}

