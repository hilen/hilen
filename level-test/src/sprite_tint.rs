use anyhow::Result;
use hilen::{
    gm::{
        Shape,
        color::{Color, RED, WHITE},
    },
    level::{Banner, LevelCreation, LevelSetup, LevelTest, SpriteTemplates, level},
    refs::Weak,
    ui_test::{check_colors, set_record_probe_count},
};

/// The same cutout four times, left to right: untinted, flashed red like a
/// hit, dimmed to half, and half transparent.
#[level]
#[derive(Default)]
struct SpriteTint {}

impl LevelSetup for SpriteTint {
    fn setup(&mut self) {
        let tints = [
            (-21, WHITE),
            (-7, RED),
            (7, Color::hex("#808080")),
            (21, WHITE.with_alpha(0.5)),
        ];
        for (x, tint) in tints {
            let mut sprite = self.make_sprite::<Banner>(Shape::Rect((6, 10).into()), (x, 0));
            sprite.set_image("game/frisk.png");
            sprite.tint = tint;
        }
    }
}

impl LevelTest for SpriteTint {
    fn perform_test(_level: Weak<Self>) -> Result<()> {
        set_record_probe_count(160);
        check_colors(TINTED)
    }
}

